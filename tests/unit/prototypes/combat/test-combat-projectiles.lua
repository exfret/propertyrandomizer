local projectiles = require("src/prototypes/combat/combat-projectiles")

local passed = 0
local function test(name, run)
    local ok, reason = pcall(run)
    assert(ok, name .. ": " .. tostring(reason))
    passed = passed + 1
end

local function close(actual, expected)
    assert(actual ~= nil and math.abs(actual - expected) < 0.000001, tostring(actual) .. " ~= " .. expected)
end

local function flight(speed, acceleration, cap, modifier)
    return assert(projectiles.flight({starting_speed = speed}, {
        acceleration = acceleration,
        max_speed = cap,
        speed_modifier = modifier,
    }))
end

local function expression(speed, acceleration, cap, modifier)
    return projectiles.follow(nil, flight(speed, acceleration, cap, modifier))
end

local function delay(value, range)
    return projectiles.delay({flight_time = value}, range, 0)
end

-- Recorded by the isolated PROJECTILEPROBE on Factorio 2.1.20, 2026-10-05.
-- These are observed positions after 120 ticks, not outputs generated by the scoring model.
test("quantization margin does not outrun measured constant-speed motion", function()
    close(delay(expression(0.1, 0), 11.71875), 125 / 60)
    close(delay(expression(1, 0), 20), 21 / 60)
end)

test("accelerating bound stays behind measured motion on both cardinal and diagonal rays", function()
    local ray = expression(0.1, 0.005)
    assert(delay(ray, 48.07421875) >= 120 / 60)
    assert(delay(ray, math.sqrt(2) * 33.9140625) >= 120 / 60)
    assert(delay(ray, 48.07421875) <= 122 / 60)
end)

test("rocket-shaped acceleration removes the initial-speed-only overestimate", function()
    close(delay(expression(0.1, 0.01), 36), 76 / 60)
    close(delay(expression(0.05, 0.005), 42.078125), 121 / 60)
end)

test("speed cap and initial speed above it preserve observed lower bounds", function()
    assert(delay(expression(0.1, 0.005, 0.2), 22.93359375) >= 120 / 60)
    assert(delay(expression(0.3, 0.005, 0.2), 23.90625) >= 120 / 60)
    close(delay(expression(0.3, 0.005, 0.2), 20), delay(expression(0.2, 0, 0.2), 20))
end)

test("anisotropic modifiers retain the conservative constant-speed fallback", function()
    local modifier = {
        x = 0.5,
        y = 2,
    }
    local accelerating = delay(expression(0.1, 0.005, nil, modifier), 20)
    close(accelerating, delay(expression(0.1, 0, nil, modifier), 20))
    assert(accelerating > delay(expression(0.1, 0.005), 20))
end)

test("parallel branches use the slowest latency and nested flights accumulate", function()
    local fast, slow = expression(1, 0), expression(0.1, 0.01)
    close(delay(projectiles.parallel(fast, slow), 20), 55 / 60)
    close(delay(projectiles.follow(slow, flight(1, 0)), 20), 76 / 60)
end)

test("shared latency subtrees consume their tick budget once", function()
    local shared = expression(0.05, 0)
    local left = projectiles.follow(shared, flight(1000, 0))
    local right = projectiles.follow(shared, flight(1000, 0))
    close(delay(projectiles.parallel(left, right), 120), delay(shared, 120) + 1 / 60)
end)

test("each profile has a fixed total simulation budget", function()
    local value, reason = delay(expression(0.1, 0), 1000)
    assert(value == nil and reason == "projectile-flight-budget")
end)

test("subpixel constant motion is not certified as progress", function()
    local value, reason = delay(expression(0.001, 0), 1)
    assert(value == nil and reason == "stationary-projectile-bound")
end)

test("negative acceleration and scatter remain unsupported", function()
    assert(projectiles.flight({starting_speed = 1}, {acceleration = -0.01}) == nil)
    assert(projectiles.flight({
        starting_speed = 1,
        starting_speed_deviation = 0.1,
    }, {acceleration = 0.01}) == nil)
end)

print("combat-projectiles: " .. passed .. " tests passed")
